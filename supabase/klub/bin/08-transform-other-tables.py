#!/usr/bin/env python3
"""
Generate sync SQL for every klub table OTHER than profiles/user_roles/
memberships (those were handled by 02-transform.py). Reads the same
export/*.json + export/id-map.json (built by 02-transform.py — run that
first). Tables with 0 rows in their export are skipped (schema already
creates them empty via 07-apply-other-schema.sh).

user_id-shaped columns are remapped through id-map.json exactly like
profiles/memberships were, so the 37 identity-merged members' rows land on
their existing (vyzva) account instead of a stray klub-only id.

Output: bin/sql/1N-<table>.sql, one INSERT ON CONFLICT (id) DO NOTHING per
table (odm_knowledge is batched, 500 rows/statement, since each row's
embedding text is ~19KB).
"""
import json
from pathlib import Path

KLUB_DIR = Path(__file__).resolve().parent.parent
EXPORT_DIR = KLUB_DIR / "export"
SQL_DIR = Path(__file__).resolve().parent / "sql"

# (table, [user-id-shaped columns to remap], depends_on_table_before_it)
# Order matters: FK dependencies must be inserted before their dependents.
TABLES = [
    ("club_events", []),
    ("event_registrations", ["user_id"]),
    ("pair_requests", ["from_user", "to_user"]),
    ("direct_messages", ["sender_id"]),
    ("ai_conversations", ["user_id"]),
    ("ai_messages", []),
    ("meal_plan_days", []),
    ("meals", []),
    ("member_recipes", ["author_id"]),
    ("club_survey", ["user_id"]),
    ("badges", []),
    ("challenge_days", []),
    ("club_sections", []),
    ("coaching_modules", []),
    ("consultation_recordings", []),
    ("content_videos", []),
    ("funnel_applications", []),
    ("invites", ["user_id"]),
    ("measurements", ["user_id"]),
    ("module_progress", ["user_id"]),
    ("monthly_themes", []),
    ("odm_knowledge", []),
    ("onboarding_answers", ["user_id"]),
    ("step_progress", ["user_id"]),
    ("survey_config", []),
    ("announcements", []),
]

ODM_BATCH_SIZE = 500


def sql_lit(v):
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, (dict, list)):
        s = json.dumps(v, ensure_ascii=False).replace("'", "''")
        return f"'{s}'"
    s = str(v).replace("'", "''")
    return f"'{s}'"


def main():
    with open(EXPORT_DIR / "id-map.json") as f:
        id_map = json.load(f)

    file_index = []  # (sql_filename, table, row_count) for the summary + runner script
    n = 10  # sql/10-*, 11-*, ... continuing after 02-04 (profiles/roles/memberships)

    for table, user_cols in TABLES:
        path = EXPORT_DIR / f"{table}.json"
        if not path.exists():
            print(f"SKIP {table}: no export file")
            continue
        rows = json.load(open(path))
        if not rows:
            print(f"SKIP {table}: 0 rows")
            continue

        cols = list(rows[0].keys())
        out_rows = []
        for row in rows:
            out = dict(row)
            for c in user_cols:
                if out.get(c):
                    out[c] = id_map.get(out[c], out[c])
            out_rows.append(out)

        fname = f"{n:02d}-{table}.sql"
        header = (
            f"-- Generated by 08-transform-other-tables.py from supabase/klub/export/{table}.json.\n"
            + (f"-- Remapped columns (identity merge): {', '.join(user_cols)}.\n" if user_cols else "")
        )

        if table == "odm_knowledge":
            # batch: one file, multiple INSERT statements (huge embedding text per row)
            parts = [header]
            for i in range(0, len(out_rows), ODM_BATCH_SIZE):
                batch = out_rows[i:i + ODM_BATCH_SIZE]
                values = ",\n".join(
                    "    (" + ", ".join(sql_lit(r[c]) for c in cols) + ")" for r in batch
                )
                parts.append(
                    f"INSERT INTO public.{table} (\n    {', '.join(cols)}\n) VALUES\n{values}\n"
                    f"ON CONFLICT DO NOTHING;\n"
                )
            (SQL_DIR / fname).write_text("\n".join(parts))
        else:
            values = ",\n".join(
                "    (" + ", ".join(sql_lit(r[c]) for c in cols) + ")" for r in out_rows
            )
            # Bare ON CONFLICT DO NOTHING (no target column): several tables
            # (e.g. meals has UNIQUE(day_number, meal_type) besides its id PK)
            # have a second unique constraint. Naming a specific conflict
            # target only suppresses violations of THAT constraint — a retry
            # after a successful run would still hard-error on the other one.
            # No target catches any unique/exclusion violation, making every
            # file safely re-runnable regardless of which constraints exist.
            sql = (
                header
                + f"INSERT INTO public.{table} (\n    {', '.join(cols)}\n) VALUES\n{values}\n"
                f"ON CONFLICT DO NOTHING;\n"
            )
            (SQL_DIR / fname).write_text(sql)

        file_index.append((fname, table, len(out_rows)))
        print(f"{table}: {len(out_rows)} rows -> sql/{fname}")
        n += 1

    with open(SQL_DIR / "_other-tables-index.json", "w") as f:
        json.dump(file_index, f, indent=2)


if __name__ == "__main__":
    main()
